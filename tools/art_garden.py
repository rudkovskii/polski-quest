"""Растения огорода в духе Stardew Valley: светлые, воздушные, с тонкими стеблями и открытыми листьями.

Рисует кусты-варианты `plant_v00…v15` (росток, кустик, урожай, основа под мини-предмет), плоды цвета `plant_fruits_*`
и общие стадии `crop_*` (семечко, росток, кустик, урожай, перезревшее). Зовут `art_plants.py` и `art_crops.py`.

Правила стиля (просьба Шэфа 19.10: «тёмный и громоздкий» → лёгкий):
  * растение меньше клетки: вокруг видна земля грядки; росток ≈ 6×4 px, кустик ≈ 10×9, урожай пышный, но со щелями;
  * свет сверху-слева: верхний-левый край листа светлый (`l`/`h`), нижний-правый — тень (`s`);
  * контур выборочный (sel-out): только снизу и справа, тёмно-зелёный/оливковый `o` (`leaf.1`), сверху-слева контура нет;
  * тень на земле короткая и тёплая (`_`, `soil.1`), справа-снизу от стебля.
Рисунки — пиксели ASCII (16 символов в строке, нижняя строка рисунка = строка 29 кадра 16×32: земля под растением).
Цвета только из палитры (имена `<материал>.<тон>`), светлые сочные зелёные — материал `sprout` (art/materials.json).
"""
from __future__ import annotations

Grid = list[list[str | None]]

# Общая легенда: листва (сочная, задняя, шалфейная), дерево, тень на земле.
BASE = {
    'h': 'sprout.3', 'l': 'sprout.2', 'm': 'leaf2.2', 's': 'leaf.2', 'o': 'leaf.1',  # сочная листва + контур
    'L': 'leaf2.2', 'M': 'leaf.2', 'S': 'leaf.1',  # задние листья (в глубине)
    'g': 'leaf2.4', 'k': 'leaf2.3', 'j': 'leaf.3',  # шалфейная листва: блик, свет, основной (тень — s)
    'y': 'petal_yellow.3',  # жёлтый блик
    'w': 'wood.3', 'W': 'wood.2', 'v': 'wood.1',  # дерево (светлое, чтобы читалось на земле): свет, основной, тень
    '_': 'soil.1',  # тень на земле
}


def accent(mat: str, core: str | None = None, mat2: str | None = None, core2: str | None = None) -> dict[str, str]:
    """Цвет цветка/плода: 1…4 — тень, основной, свет, блик; 0 — серединка; 5…8 и 9 — второй цвет."""
    d = {str(i): f'{mat}.{i}' for i in range(1, 5)}
    if core:
        d['0'] = core
    if mat2:
        d.update({str(4 + i): f'{mat2}.{i}' for i in range(1, 5)})
    if core2:
        d['9'] = core2
    return d


def grid(art: str, legend: dict[str, str] | None = None, w: int = 16, h: int = 32, bottom: int | None = None) -> Grid:
    """ASCII → кадр w×h; последняя строка рисунка ложится на строку `bottom` (по умолчанию h − 3)."""
    rows = [r.strip() for r in art.strip('\n').split('\n')]
    rows = [r for r in rows if r]
    bottom = h - 3 if bottom is None else bottom
    out: Grid = [[None] * w for _ in range(h)]
    top = bottom - len(rows) + 1
    if top < 0:
        raise SystemExit(f'рисунок выше кадра: {len(rows)} строк')
    lg = {**BASE, **(legend or {})}
    for i, r in enumerate(rows):
        if len(r) != w:
            raise SystemExit(f'строка {i} длиной {len(r)}, нужно {w}: {r!r}')
        for x, ch in enumerate(r):
            if ch == '.':
                continue
            if ch not in lg:
                raise SystemExit(f'символ {ch!r} без цвета в легенде')
            out[top + i][x] = lg[ch]
    return out


